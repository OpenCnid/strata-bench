import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { Ajv2020 } from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

export async function validatorSource() {
  // Exact existing runtime policy. Build-time compilation never moves game or
  // authority initialization out of the worker's fixed deadlines.
  const ajv = new Ajv2020({strict: false, strictNumbers: true, allErrors: false,
    coerceTypes: false, code: {source: true, esm: true, lines: true}});
  addFormats(ajv);
  const schemaHashes = {};
  const exports = {};
  for (const name of ['ActionBatch', 'ActionAck', 'Observation', 'RpcRequest']) {
    const bytes = await readFile(new URL(`../../../schemas/v1/public/${name}.json`, import.meta.url));
    schemaHashes[name] = createHash('sha256').update(bytes).digest('hex');
    ajv.addSchema(JSON.parse(bytes), name);
    exports[name] = name;
  }
  return '// @ts-nocheck\n// Generated by npm run generate; do not edit. Ajv 8.20.0 / ajv-formats 3.0.1.\n'
    + 'import {createRequire} from "node:module";\nconst require = createRequire(import.meta.url);\n'
    + `export const schemaHashes = ${JSON.stringify(schemaHashes, null, 2)};\n`
    + standaloneCode(ajv, exports).trimEnd() + '\n';
}

if (process.argv[2] === '--check') {
  const actual = await readFile(new URL('../src/schema_validators.ts', import.meta.url), 'utf8');
  if (actual !== await validatorSource()) throw new Error('SCHEMA_BUILD_STALE: run npm run generate');
}
